STOCK_KEYS = ("o", "h", "l", "c", "prev", "pct", "amp", "vol", "turn")
IDX_KEYS = ("o", "h", "l", "c", "prev", "pct", "amp", "vol", "amount")


def bar_to_dict(keys, bar):
    return {k: v for k, v in zip(keys, bar[1:])}


def check_anchor_and_tdx(errors):
    """A: 10-14 锚点比对旧文件；B: 全 5 根 OHLC/vol 交叉比对 TDX 独立源"""
    tdx = json.load(open(os.path.join(RAW, "pattern_pool_klines_2y.json"), encoding="utf-8"))
    tdx_stocks = tdx["stocks"]
    tdx_idx = tdx["index"]["000001"]["bars"]

    for code, (name, bars) in TAIL.items():
        fn = "market_full_6m.json" if code in MAIN_CODES else "market_full_ext_6m.json"
        old = json.load(open(os.path.join(RAW, fn), encoding="utf-8"))["daily"][code]["d"]
        for bar in bars:
            d = bar[0]
            rec = bar_to_dict(STOCK_KEYS, bar)
            # A. 锚点（10-14 必须与旧文件一致）
            if d in old:
                ob = old[d]
                for k in STOCK_KEYS:
                    tol = 1.0 if k == "vol" else (0.051 if k == "turn" else 0.011)
                    if abs((ob.get(k) or 0) - rec[k]) > tol:
                        errors.append(f"A-锚点 {code}@{d} {k}: 旧={ob.get(k)} 新={rec[k]}")
            # B. TDX 独立源（OHLC 全等，vol=TDX×100±150）——TDX 文件键为裸代码
            tdx_bar = next((b for b in tdx_stocks[code.split(".")[0]]["bars"] if b[0] == d), None)
            if not tdx_bar:
                errors.append(f"B-TDX {code}@{d} 缺失")
                continue
            for i, k in enumerate(("o", "c", "h", "l")):
                if abs(rec[k] - tdx_bar[1 + i]) > 0.0011:
                    errors.append(f"B-TDX {code}@{d} {k}: neodata={rec[k]} tdx={tdx_bar[1+i]}")
            if abs(rec["vol"] - tdx_bar[5] * 100) > 150:
                errors.append(f"B-TDX {code}@{d} vol: neodata={rec['vol']} tdx×100={tdx_bar[5]*100}")

    # 指数
    old_idx = json.load(open(os.path.join(RAW, "index_daily.json"), encoding="utf-8"))["daily"]["000001.SH"]["d"]
    for bar in IDX_TAIL:
        d = bar[0]
        rec = bar_to_dict(IDX_KEYS, bar)
        if d in old_idx:
            ob = old_idx[d]
            for k in ("o", "h", "l", "c", "vol", "amount"):
                if abs((ob.get(k) or 0) - rec[k]) > max(1.0, abs(rec[k]) * 1e-6):
                    errors.append(f"A-锚点 指数@{d} {k}: 旧={ob.get(k)} 新={rec[k]}")
        tdx_bar = next((b for b in tdx_idx if b[0] == d), None)
        if not tdx_bar:
            errors.append(f"B-TDX 指数@{d} 缺失")
            continue
        for i, k in enumerate(("o", "c", "h", "l")):
            if abs(rec[k] - tdx_bar[1 + i]) > 0.011:
                errors.append(f"B-TDX 指数@{d} {k}: neodata={rec[k]} tdx={tdx_bar[1+i]}")


def main():
    global MAIN_CODES
    main_data = json.load(open(os.path.join(RAW, "market_full_6m.json"), encoding="utf-8"))
    MAIN_CODES = set(main_data["daily"].keys())

    errors = []
    check_anchor_and_tdx(errors)
    if errors:
        print("校验失败，拒绝合并：")
        for e in errors:
            print("  " + e)
        sys.exit(1)
    print("校验通过：A 锚点 27 票×9 字段 + 指数 6 字段与旧文件一致；B 全部 OHLC 与 TDX 独立源一致、vol=TDX×100±150")

    # ---- 合并股票 ----
    added_total = 0
    for code, (name, bars) in TAIL.items():
        fn = "market_full_6m.json" if code in MAIN_CODES else "market_full_ext_6m.json"
        path = os.path.join(RAW, fn)
        data = json.load(open(path, encoding="utf-8"))
        blk = data["daily"][code]
        if blk.get("name") and blk["name"] != name:
            print(f"  警告 {code} 名称不一致: 旧={blk['name']} 新={name}（保留旧名）")
        for bar in bars:
            d = bar[0]
            if d in blk["d"]:
                continue
            blk["d"][d] = bar_to_dict(STOCK_KEYS, bar)
            added_total += 1
        blk["d"] = dict(sorted(blk["d"].items()))
        data["_meta"]["extended_20261021"] = (
            "2026-10-21 追加 2026-10-15~20 日K（neodata quote_and_kline 不复权，"
            "与初始数据同源；10-14 锚点复拉一致，OHLC 与 TDX 独立源交叉一致）")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False)
    print(f"股票合并完成：新增 {added_total} 根 bar（27 只票 × 4 个新交易日）")

    # ---- 合并指数 ----
    path = os.path.join(RAW, "index_daily.json")
    data = json.load(open(path, encoding="utf-8"))
    blk = data["daily"]["000001.SH"]
    added = 0
    for bar in IDX_TAIL:
        d = bar[0]
        if d in blk["d"]:
            continue
        blk["d"][d] = bar_to_dict(IDX_KEYS, bar)
        added += 1
    blk["d"] = dict(sorted(blk["d"].items()))
    data["extended_20261021"] = "2026-10-21 追加 2026-10-15~20 上证指数日K（neodata，仅收盘价参与 regime 计算）"
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)
    print(f"指数合并完成：新增 {added} 根 bar")

    # ---- 汇总 ----
    for fn in ("market_full_6m.json", "market_full_ext_6m.json", "index_daily.json"):
        d = json.load(open(os.path.join(RAW, fn), encoding="utf-8"))
        if fn == "index_daily.json":
            inner = d["daily"]["000001.SH"]["d"]
            ds = sorted(inner.keys())
            print(f"{fn}: {ds[0]} ~ {ds[-1]}（{len(ds)}天）")
        else:
            ds = sorted(next(iter(d["daily"].values()))["d"].keys())
            print(f"{fn}: {ds[0]} ~ {ds[-1]}（{len(ds)}天，{len(d['daily'])}只）")


if __name__ == "__main__":
    main()
